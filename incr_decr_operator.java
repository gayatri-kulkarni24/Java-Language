import java.util.*;
public class javaBasics{
    public static void main(String[] args){
       int a=10;
       System.out.println(++a);//11 use
       System.out.println(a);
       System.out.println(a++);//11 12
       System.out.println(a);
       System.out.println(--a);//12 11 use
       System.out.println(a);
       System.out.println(a--);//11 10
       System.out.println(a);
 
    }
}
